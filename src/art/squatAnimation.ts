export type RepPhase = 'BRACE' | 'DESCENT' | 'HOLE' | 'ASCENT' | 'LOCKOUT';

export const REP_PHASES: readonly RepPhase[] = [
  'BRACE',
  'DESCENT',
  'HOLE',
  'ASCENT',
  'LOCKOUT',
];

/** State of the lift on one 60 Hz tick. */
export interface SquatSample {
  readonly tick: number;
  readonly phase: RepPhase;
  readonly direction: RepDirection;
  /** 0 = standing, 1 = bottom of the hole. */
  readonly depth: number;
  /** 1 - depth. Normalised bar height; the velocity model's variable. */
  readonly barHeight: number;
  /** Bar centre-line in sprite px, from the rig's own drawings. */
  readonly barYPx: number;
  /** Sagittal drift toward the toes, px. Not drawn in a front view. */
  readonly barForwardPx: number;
  /** Frontal-plane offset of the bar centre, px. Drawn. */
  readonly barLateralPx: number;
  /** Bar tilt, degrees, positive = lifter's right side high. Drawn. */
  readonly barTiltDeg: number;
  /** Sleeve droop from whip, px. Drawn. */
  readonly barBendPx: number;
  readonly strain: number;
  readonly chalkPuff: number;
}

/** One displayed animation frame: a drawing plus how long it is held. */
export interface SquatFrame {
  readonly index: number;
  readonly startTick: number;
  readonly holdTicks: number;
  readonly phase: RepPhase;
  readonly direction: RepDirection;
  /** Depth quantised to the sheet's authored steps. Identifies the drawing. */
  readonly poseDepth: number;
  readonly strainLevel: number;
  /** Quantised body response to sagittal forward drift. See the header. */
  readonly pitchLevel: number;
  readonly barLateralPx: number;
  readonly barTiltDeg: number;
  readonly barBendPx: number;
  readonly chalkMotes: number;
  /** Un-quantised state at the tick this frame starts on, for data consumers. */
  readonly sample: SquatSample;
}

export interface SquatRep {
  readonly loadRatio: number;
  readonly samples: readonly SquatSample[];
  readonly frames: readonly SquatFrame[];
  readonly totalTicks: number;
  readonly totalMs: number;
  readonly phaseTicks: Readonly<Record<RepPhase, number>>;
}

// ---------------------------------------------------------------------------
// Quantisation of drawn state. A 16-bit game ships a finite sheet; continuous
// per-frame deformation is a modern-engine tell. These say how finite, and they
// are tunables, so they live in spriteTuning.QUANTISE. Re-exported here under
// their working names because this is the module that uses them.
// ---------------------------------------------------------------------------

export const DEPTH_STEPS = QUANTISE.DEPTH_STEPS;
export const TILT_QUANTUM_DEG = QUANTISE.TILT_QUANTUM_DEG;
export const BEND_QUANTUM_PX = QUANTISE.BEND_QUANTUM_PX;

function clamp01(v: number): number {
  return Math.min(1, Math.max(0, v));
}

function gauss(x: number, center: number, width: number): number {
  const z = (x - center) / width;
  return Math.exp(-z * z);
}

function quantize(value: number, step: number): number {
  return Math.round(value / step) * step;
}

/** Centred moving average, clamped at the ends. Window is forced odd. */
function movingAverage(values: readonly number[], window: number): number[] {
  const half = Math.max(0, Math.floor(window / 2));
  return values.map((_, i) => {
    let sum = 0;
    let n = 0;
    for (let k = i - half; k <= i + half; k += 1) {
      const v = values[Math.min(values.length - 1, Math.max(0, k))];
      if (v === undefined) continue;
      sum += v;
      n += 1;
    }
    return n === 0 ? 0 : sum / n;
  });
}

// ---------------------------------------------------------------------------
// Ascent velocity model
// ---------------------------------------------------------------------------

/**
 * Grid resolution for integrating dt = dh / v(h).
 *
 * Deliberately NOT in spriteTuning: this is numerical accuracy, not feel.
 * Doubling it does not change how the rep looks, only how exactly the integral
 * is evaluated. STICK.MIN_VELOCITY, which does change how the rep looks, is a
 * tunable and lives there.
 */
const VELOCITY_GRID = 1024;

/**
 * Normalised ascent velocity at bar height h.
 * Exported so the inspection tool can plot the same curve the frames come from
 * rather than a redrawn approximation of it.
 */
export function ascentVelocity(h: number, loadRatio: number): number {
  const depth = byLoad(STICK.DEPTH, loadRatio);
  const v = 1 - depth * gauss(h, STICK.HEIGHT_FRAC, STICK.WIDTH);
  return Math.max(STICK.MIN_VELOCITY, v);
}

/**
 * Invert the time integral: bar height as a function of normalised ascent time.
 * Returns a lookup closure so a whole rep costs one integration.
 */
function ascentHeightSampler(loadRatio: number): (u: number) => number {
  const heights = new Float64Array(VELOCITY_GRID + 1);
  const times = new Float64Array(VELOCITY_GRID + 1);
  const dh = 1 / VELOCITY_GRID;

  let t = 0;
  heights[0] = 0;
  times[0] = 0;
  for (let j = 1; j <= VELOCITY_GRID; j += 1) {
    const hPrev = (j - 1) * dh;
    const hCur = j * dh;
    // Trapezoid on 1/v, which is where the time actually accumulates.
    const inv = 0.5 * (1 / ascentVelocity(hPrev, loadRatio) + 1 / ascentVelocity(hCur, loadRatio));
    t += inv * dh;
    heights[j] = hCur;
    times[j] = t;
  }

  const total = times[VELOCITY_GRID] ?? 1;
  for (let j = 0; j <= VELOCITY_GRID; j += 1) {
    times[j] = (times[j] ?? 0) / total;
  }

  return (u: number): number => {
    const target = clamp01(u);
    // times[] is strictly increasing, so a binary search is exact enough.
    let lo = 0;
    let hi = VELOCITY_GRID;
    while (hi - lo > 1) {
      const mid = (lo + hi) >> 1;
      if ((times[mid] ?? 0) <= target) lo = mid;
      else hi = mid;
    }
    const tLo = times[lo] ?? 0;
    const tHi = times[hi] ?? 1;
    const hLo = heights[lo] ?? 0;
    const hHi = heights[hi] ?? 1;
    const span = tHi - tLo;
    const f = span <= 0 ? 0 : (target - tLo) / span;
    return clamp01(hLo + (hHi - hLo) * f);
  };
}

// ---------------------------------------------------------------------------
// Per-phase depth
// ---------------------------------------------------------------------------

function descentDepth(u: number, loadRatio: number): number {
  const mix = byLoad(DESCENT.SMOOTHSTEP_MIX, loadRatio);
  const smooth = u * u * (3 - 2 * u);
  const shaped = (1 - mix) * u + mix * smooth;
  return BRACE_SETTLE_DEPTH + (1 - BRACE_SETTLE_DEPTH) * shaped;
}

// ---------------------------------------------------------------------------
// Bar path
// ---------------------------------------------------------------------------

function forwardDriftDescent(depth: number, loadRatio: number): number {
  const atHole = byLoad(BAR_PATH.FORWARD_AT_HOLE_PX, loadRatio);
  // Drift accumulates late in the eccentric, as the hips travel back.
  return atHole * Math.pow(clamp01(depth), BAR_PATH.FORWARD_DESCENT_EXPONENT);
}

function forwardDriftAscent(h: number, loadRatio: number): number {
  const atHole = byLoad(BAR_PATH.FORWARD_AT_HOLE_PX, loadRatio);
  const peak = byLoad(BAR_PATH.FORWARD_PX, loadRatio);
  const carried = atHole * (1 - h);
  const fight = peak * gauss(h, BAR_PATH.FORWARD_PEAK_FRAC, BAR_PATH.FORWARD_PEAK_WIDTH) * (1 - h);
  return carried + fight;
}

/**
 * Frontal-plane wobble during the grind: a steady lean plus a shake.
 * Both are gated by an envelope centred on the sticking point, so a rep that
 * never really stalls never really shakes.
 */
function grindWobble(
  h: number,
  tickInPhase: number,
  loadRatio: number,
): { lateral: number; tiltDeg: number } {
  const envelope = gauss(h, STICK.HEIGHT_FRAC, STICK.WIDTH * STICK.WOBBLE_ENVELOPE_WIDEN);
  const phase = (2 * Math.PI * tickInPhase) / STICK.OSCILLATION_PERIOD_TICKS;
  const shake = byLoad(STICK.OSCILLATION_PX, loadRatio) * Math.sin(phase);
  const lean = byLoad(BAR_PATH.LATERAL_PX, loadRatio);
  const tilt = byLoad(BAR_PATH.TILT_DEG, loadRatio);
  return {
    lateral: envelope * (lean * BAR_PATH.LATERAL_LEAN_SHARE + shake),
    tiltDeg: envelope * tilt * Math.cos(phase),
  };
}

// ---------------------------------------------------------------------------
// Strain
// ---------------------------------------------------------------------------

function phaseWeight(phase: RepPhase, depth: number, h: number): number {
  const w = STRAIN.PHASE_WEIGHT;
  switch (phase) {
    case 'BRACE':
      return w.BRACE;
    case 'DESCENT':
      return w.DESCENT_TOP + (w.DESCENT_BOTTOM - w.DESCENT_TOP) * clamp01(depth);
    case 'HOLE':
      return w.HOLE;
    case 'ASCENT':
      return clamp01(
        w.ASCENT_BASE -
          w.ASCENT_FALLOFF * h +
          w.ASCENT_STICK_BONUS * gauss(h, STICK.HEIGHT_FRAC, w.ASCENT_STICK_WIDTH),
      );
    case 'LOCKOUT':
      return w.LOCKOUT;
    default:
      return 0;
  }
}

/**
 * Strain at a point in the rep.
 *
 * Load times where-you-are, and nothing else. Forward bar drift used to be
 * added in here with a gain; it is not, and must not come back. On a maximal
 * grind — the only rep whose drift is worth drawing — the load term is already
 * near the top of the range and anything added to it is clamped straight back
 * off, so the drift's contribution reached the pixels of the LIGHT rep only.
 * Drift is now its own channel (`pitchLevelForDriftPx`), which is what lets it
 * be seen on the rep that has it.
 */
function strainFor(phase: RepPhase, depth: number, h: number, loadRatio: number): number {
  const base = byLoad(STRAIN.FROM_LOAD, loadRatio);
  return clamp01(base * phaseWeight(phase, depth, h));
}

