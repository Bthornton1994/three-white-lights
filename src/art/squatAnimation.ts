interface RawTick {
  phase: RepPhase;
  direction: RepDirection;
  depth: number;
  forwardPx: number;
  lateralPx: number;
  tiltDeg: number;
  chalkPuff: number;
}

/** Tick counts per phase at a given load. Exported for the inspection tool. */
export function phaseTickCounts(loadRatio: number): Record<RepPhase, number> {
  return {
    BRACE: ticksByLoad(TIMING.BRACE_TICKS, loadRatio),
    DESCENT: ticksByLoad(TIMING.DESCENT_TICKS, loadRatio),
    HOLE: ticksByLoad(TIMING.HOLE_TICKS, loadRatio),
    ASCENT: ticksByLoad(TIMING.ASCENT_TICKS, loadRatio),
    LOCKOUT: ticksByLoad(TIMING.LOCKOUT_TICKS, loadRatio),
  };
}

/**
 * Build one squat rep.
 *
 * `loadRatio` is attempt weight over current best single: 0.55 is a comfortable
 * working set, 1.0 is a true limit attempt. Values outside LOAD_RANGE clamp.
 */
export function buildSquatRep(loadRatio: number): SquatRep {
  const load = clampLoadRatio(loadRatio);
  const counts = phaseTickCounts(load);
  const heightAt = ascentHeightSampler(load);

  const raw: RawTick[] = [];

  for (let k = 0; k < counts.BRACE; k += 1) {
    const u = counts.BRACE <= 1 ? 1 : k / (counts.BRACE - 1);
    raw.push({
      phase: 'BRACE',
      direction: 'DESCENT',
      depth: BRACE_SETTLE_DEPTH * u,
      forwardPx: 0,
      lateralPx: 0,
      tiltDeg: 0,
      chalkPuff: 0,
    });
  }

  for (let k = 0; k < counts.DESCENT; k += 1) {
    const depth = descentDepth(k / counts.DESCENT, load);
    raw.push({
      phase: 'DESCENT',
      direction: 'DESCENT',
      depth,
      forwardPx: forwardDriftDescent(depth, load),
      lateralPx: 0,
      tiltDeg: 0,
      chalkPuff: 0,
    });
  }

  for (let k = 0; k < counts.HOLE; k += 1) {
    raw.push({
      phase: 'HOLE',
      direction: 'DESCENT',
      depth: 1,
      forwardPx: forwardDriftDescent(1, load),
      lateralPx: 0,
      tiltDeg: 0,
      chalkPuff: 0,
    });
  }

  const chalkActive = load >= CHALK.MIN_LOAD_RATIO;
  for (let k = 0; k < counts.ASCENT; k += 1) {
    const h = heightAt(k / counts.ASCENT);
    const wobble = grindWobble(h, k, load);
    raw.push({
      phase: 'ASCENT',
      direction: 'ASCENT',
      depth: 1 - h,
      forwardPx: forwardDriftAscent(h, load),
      lateralPx: wobble.lateral,
      tiltDeg: wobble.tiltDeg,
      chalkPuff: chalkActive && k < CHALK.PUFF_TICKS ? 1 - k / CHALK.PUFF_TICKS : 0,
    });
  }

  for (let k = 0; k < counts.LOCKOUT; k += 1) {
    raw.push({
      phase: 'LOCKOUT',
      direction: 'ASCENT',
      depth: 0,
      forwardPx: 0,
      lateralPx: 0,
      tiltDeg: 0,
      chalkPuff: 0,
    });
  }

  // Bar whip needs the second difference of bar height, so it is a second pass.
  const barY = raw.map((r) => barYAtDepth(r.depth));
  const barYSmooth = movingAverage(barY, BEND.ACCEL_SMOOTH_TICKS);
  const staticBend = byLoad(BEND.STATIC_PX, load);

  const samples: SquatSample[] = raw.map((r, k) => {
    const yPrev = barYSmooth[k - 1] ?? barYSmooth[k] ?? 0;
    const yCur = barYSmooth[k] ?? 0;
    const yNext = barYSmooth[k + 1] ?? yCur;
    // Screen y grows downward, so upward acceleration is the negated second
    // difference. Decelerating into the hole and accelerating out of it both
    // come out positive, which is what loads the bar and bows the sleeves.
    const upAccel = -(yNext - 2 * yCur + yPrev);
    const whip = Math.min(
      BEND.MAX_WHIP_MULTIPLIER,
      Math.max(0, 1 + BEND.WHIP_GAIN * upAccel),
    );
    const bend = Math.min(BEND.MAX_PX, staticBend * whip);
    const h = 1 - r.depth;

    return {
      tick: k,
      phase: r.phase,
      direction: r.direction,
      depth: r.depth,
      barHeight: h,
      barYPx: yCur,
      barForwardPx: r.forwardPx,
      barLateralPx: r.lateralPx,
      barTiltDeg: r.tiltDeg,
      barBendPx: bend,
      strain: strainFor(r.phase, r.depth, h, load),
      chalkPuff: r.chalkPuff,
    };
  });

  const frames = coalesceFrames(samples);
  const totalTicks = samples.length;

  return {
    loadRatio: load,
    samples,
    frames,
    totalTicks,
    totalMs: totalTicks * TICK_MS,
    phaseTicks: counts,
  };
}

/** The drawn identity of a tick. Two ticks that agree here are one frame. */
interface DrawKey {
  phase: RepPhase;
  direction: RepDirection;
  poseDepth: number;
  strainLevel: number;
  pitchLevel: number;
  lateral: number;
  tilt: number;
  bend: number;
  motes: number;
}

function drawKeyFor(s: SquatSample): DrawKey {
  return {
    phase: s.phase,
    direction: s.direction,
    poseDepth: Math.round(clamp01(s.depth) * DEPTH_STEPS) / DEPTH_STEPS,
    strainLevel: strainLevel(s.strain),
    pitchLevel: pitchLevelForDriftPx(s.barForwardPx),
    lateral: Math.round(s.barLateralPx),
    tilt: quantize(s.barTiltDeg, TILT_QUANTUM_DEG),
    bend: quantize(s.barBendPx, BEND_QUANTUM_PX),
    motes: Math.round(s.chalkPuff * CHALK.MAX_MOTES),
  };
}

function sameDrawing(a: DrawKey, b: DrawKey): boolean {
  return (
    a.phase === b.phase &&
    a.direction === b.direction &&
    a.poseDepth === b.poseDepth &&
    a.strainLevel === b.strainLevel &&
    a.pitchLevel === b.pitchLevel &&
    a.lateral === b.lateral &&
    a.tilt === b.tilt &&
    a.bend === b.bend &&
    a.motes === b.motes
  );
}

/**
 * Collapse per-tick state into held frames.
 *
 * This is the animator's timing sheet, and it falls out of the model rather
 * than being authored: at a light load the drawings change nearly every tick,
 * and at the sticking point of a maximal attempt one drawing holds for a long
 * run of ticks because nothing about it has changed enough to redraw. Long
 * holds in the middle of the ascent ARE the grind.
 */
function coalesceFrames(samples: readonly SquatSample[]): SquatFrame[] {
  const frames: SquatFrame[] = [];
  let runStart = 0;

  while (runStart < samples.length) {
    const first = samples[runStart];
    if (first === undefined) break;
    const key = drawKeyFor(first);

    let end = runStart + 1;
    while (end < samples.length) {
      const next = samples[end];
      if (next === undefined) break;
      if (!sameDrawing(key, drawKeyFor(next))) break;
      end += 1;
    }

    frames.push({
      index: frames.length,
      startTick: runStart,
      holdTicks: end - runStart,
      phase: key.phase,
      direction: key.direction,
      poseDepth: key.poseDepth,
      strainLevel: key.strainLevel,
      pitchLevel: key.pitchLevel,
      barLateralPx: key.lateral,
      barTiltDeg: key.tilt,
      barBendPx: key.bend,
      chalkMotes: key.motes,
      sample: first,
    });

    runStart = end;
  }

  return frames;
}

// ---------------------------------------------------------------------------
// Analysis. Plain, boring functions — the tests and the inspection tool both
// use these, so they must not be clever enough to hide a problem.
// ---------------------------------------------------------------------------

export function ascentSamples(rep: SquatRep): readonly SquatSample[] {
  return rep.samples.filter((s) => s.phase === 'ASCENT');
}

/** Per-tick rise in normalised bar height during the ascent. */
export function ascentRisePerTick(rep: SquatRep): number[] {
  const asc = ascentSamples(rep);
  const out: number[] = [];
  for (let i = 1; i < asc.length; i += 1) {
    const a = asc[i - 1];
    const b = asc[i];
    if (a === undefined || b === undefined) continue;
    out.push(b.barHeight - a.barHeight);
  }
  return out;
}

export interface StallRun {
  readonly ticks: number;
  /** Normalised bar height where the longest stall begins. */
  readonly atHeight: number;
}

/**
 * Longest run of consecutive ascent ticks whose rise is below
 * STICK.STALL_EPSILON. This is the grind, measured rather than asserted.
 */
export function longestStall(rep: SquatRep): StallRun {
  const asc = ascentSamples(rep);
  const rises = ascentRisePerTick(rep);
  let best = 0;
  let bestStart = 0;
  let run = 0;
  let runStart = 0;

  for (let i = 0; i < rises.length; i += 1) {
    const rise = rises[i] ?? Number.POSITIVE_INFINITY;
    if (rise < STICK.STALL_EPSILON) {
      if (run === 0) runStart = i;
      run += 1;
      if (run > best) {
        best = run;
        bestStart = runStart;
      }
    } else {
      run = 0;
    }
  }

  return { ticks: best, atHeight: asc[bestStart]?.barHeight ?? 0 };
}

/**
 * Ascent bar height resampled to `steps` equally spaced points in NORMALISED
 * time. Duration is divided out, so anything this measures is shape.
 */
export function normalisedAscentProfile(rep: SquatRep, steps: number): number[] {
  const asc = ascentSamples(rep);
  if (asc.length === 0) return [];
  const out: number[] = [];
  for (let i = 0; i < steps; i += 1) {
    const u = steps <= 1 ? 0 : i / (steps - 1);
    const pos = u * (asc.length - 1);
    const lo = Math.floor(pos);
    const hi = Math.min(asc.length - 1, lo + 1);
    const f = pos - lo;
    const a = asc[lo]?.barHeight ?? 0;
    const b = asc[hi]?.barHeight ?? a;
    out.push(a + (b - a) * f);
  }
  return out;
}

/**
 * Coefficient of variation of the resampled ascent's step sizes.
 *
 * Zero means the bar rose at a perfectly constant rate. Large means the rep had
 * fast parts and near-stopped parts. Because the profile is in normalised time,
 * a rep that is simply a slowed-down copy of another scores IDENTICALLY. This
 * is the number that separates "heavier" from "slower".
 */
export function ascentShapeVariation(rep: SquatRep, steps: number = 64): number {
  const profile = normalisedAscentProfile(rep, steps);
  const deltas: number[] = [];
  for (let i = 1; i < profile.length; i += 1) {
    deltas.push((profile[i] ?? 0) - (profile[i - 1] ?? 0));
  }
  if (deltas.length === 0) return 0;
  const mean = deltas.reduce((a, b) => a + b, 0) / deltas.length;
  if (mean === 0) return 0;
  const variance = deltas.reduce((a, d) => a + (d - mean) * (d - mean), 0) / deltas.length;
  return Math.sqrt(variance) / Math.abs(mean);
}

/** Peak sagittal deviation of the bar from the vertical, px. */
export function peakForwardDeviationPx(rep: SquatRep): number {
  return rep.samples.reduce((m, s) => Math.max(m, Math.abs(s.barForwardPx)), 0);
}

/** Peak frontal-plane deviation of the bar centre, px. */
export function peakLateralDeviationPx(rep: SquatRep): number {
  return rep.samples.reduce((m, s) => Math.max(m, Math.abs(s.barLateralPx)), 0);
}

export function peakBendPx(rep: SquatRep): number {
  return rep.samples.reduce((m, s) => Math.max(m, s.barBendPx), 0);
}

/** Share of the rep's ticks spent in the concentric. */
export function ascentTickFraction(rep: SquatRep): number {
  return rep.totalTicks === 0 ? 0 : rep.phaseTicks.ASCENT / rep.totalTicks;
}

/** Longest single held frame, in ticks. */
export function longestHoldTicks(rep: SquatRep): number {
  return rep.frames.reduce((m, f) => Math.max(m, f.holdTicks), 0);
}

/**
 * Longest held frame within the concentric.
 *
 * The plain `longestHoldTicks` is usually won by the setup brace, where the
 * lifter is standing still on purpose and nothing is being ground out.
 *
 * NOTE, because it is easy to over-read: this does NOT go up much with load,
 * and that is correct rather than a failure. During a grind the drawing keeps
 * changing every couple of ticks — the bar shakes and tilts even though it is
 * not rising — so the ticks pile up in a short cycle of frames rather than in
 * one long hold. `longestAscentPoseRunTicks` is the metric that captures "the
 * bar stopped moving"; this one captures "the drawing stopped changing", and a
 * grinding sprite should fail the second while passing the first.
 */
export function longestAscentHoldTicks(rep: SquatRep): number {
  return rep.frames
    .filter((f) => f.phase === 'ASCENT')
    .reduce((m, f) => Math.max(m, f.holdTicks), 0);
}

/**
 * Longest run of consecutive concentric ticks that resolve to the same authored
 * depth step — i.e. how long the bar sits at one height while the lifter fights
 * it. This is the drawing-level statement of the sticking point.
 */
export function longestAscentPoseRunTicks(rep: SquatRep): number {
  const asc = ascentSamples(rep);
  let best = 0;
  let run = 0;
  let prev: number | null = null;
  for (const s of asc) {
    const step = Math.round(clamp01(s.depth) * DEPTH_STEPS);
    if (prev !== null && step === prev) run += 1;
    else run = 1;
    prev = step;
    if (run > best) best = run;
  }
  return best;
}

/**
 * Distinct BODY drawings a rep needs — i.e. how much sheet the lifter costs.
 *
 * Deliberately keyed on the body's own state only. Bar bend, tilt and lateral
 * shake are drawn on the bar, not on him, and counting them here would let a
 * shaking barbell inflate the figure "the lifter is more animated under load".
 */
export function distinctDrawingCount(rep: SquatRep): number {
  const seen = new Set<string>();
  for (const f of rep.frames) {
    seen.add(`${f.direction}:${f.poseDepth}:${f.strainLevel}:${f.pitchLevel}`);
  }
  return seen.size;
}

/** Highest strain level the rep ever draws. */
export function peakStrainLevel(rep: SquatRep): number {
  return rep.frames.reduce((m, f) => Math.max(m, f.strainLevel), 0);
}

/** Highest pitch level the rep ever draws. */
export function peakPitchLevel(rep: SquatRep): number {
  return rep.frames.reduce((m, f) => Math.max(m, f.pitchLevel), 0);
}

/**
 * The frame a rep is drawing at its sticking point — the ugliest frame it has.
 *
 * Defined as the concentric frame whose sample is nearest STICK.HEIGHT_FRAC,
 * so it is the same point of the lift for every load rather than the same tick.
 * This is the frame the light-vs-maximal body comparison is made at.
 */
export function stickingPointFrame(rep: SquatRep): SquatFrame | undefined {
  let best: SquatFrame | undefined;
  let bestErr = Infinity;
  for (const f of rep.frames) {
    if (f.phase !== 'ASCENT') continue;
    const err = Math.abs(f.sample.barHeight - STICK.HEIGHT_FRAC);
    if (err < bestErr) {
      bestErr = err;
      best = f;
    }
  }
  return best;
}

/** Convenience: the two reps the contact sheet compares. */
export function buildComparisonPair(): { light: SquatRep; maximal: SquatRep } {
  return {
    light: buildSquatRep(LOAD_PRESETS.LIGHT),
    maximal: buildSquatRep(LOAD_PRESETS.MAXIMAL),
  };
}
